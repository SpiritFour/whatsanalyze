/**
 * Writes utils/pdf/chatFontCoverage.ts: for each font choice of the
 * WhatsApp-to-PDF tool, the Unicode code points it has glyphs for, as ranges.
 *
 * The tool offers a font only when it can draw every letter of the chat, so
 * it needs each font's real character map, not a guess by script name (Courier
 * Prime, for one, has no Cyrillic). Read from the TTFs' `cmap` tables, formats
 * 4 and 12, which is what these fonts use.
 *
 * Run after upgrading a font package:  node scripts/build-font-coverage.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { resolve } from "node:path";

const require = createRequire(import.meta.url);

const FONTS = {
  serif: "@expo-google-fonts/lora/400Regular/Lora_400Regular.ttf",
  rounded: "@expo-google-fonts/nunito/400Regular/Nunito_400Regular.ttf",
  typewriter:
    "@expo-google-fonts/courier-prime/400Regular/CourierPrime_400Regular.ttf",
};

function codePoints(file) {
  const data = readFileSync(require.resolve(file));
  const view = new DataView(data.buffer, data.byteOffset, data.byteLength);
  const tables = view.getUint16(4);
  let cmap = -1;
  for (let i = 0; i < tables; i++) {
    const record = 12 + i * 16;
    const tag = data.toString("latin1", record, record + 4);
    if (tag === "cmap") cmap = view.getUint32(record + 8);
  }
  if (cmap < 0) throw new Error(`${file}: no cmap table`);

  const points = new Set();
  const subtables = view.getUint16(cmap + 2);
  for (let i = 0; i < subtables; i++) {
    const platform = view.getUint16(cmap + 4 + i * 8);
    const encoding = view.getUint16(cmap + 6 + i * 8);
    // Unicode subtables only: platform 0, or Windows (3) BMP (1) / full (10).
    if (!(
      platform === 0 ||
      (platform === 3 && (encoding === 1 || encoding === 10))
    )) {
      continue;
    }
    const at = cmap + view.getUint32(cmap + 8 + i * 8);
    const format = view.getUint16(at);

    if (format === 4) {
      const segments = view.getUint16(at + 6) / 2;
      const ends = at + 14;
      const starts = ends + segments * 2 + 2;
      const deltas = starts + segments * 2;
      const offsets = deltas + segments * 2;
      for (let s = 0; s < segments; s++) {
        const end = view.getUint16(ends + s * 2);
        const start = view.getUint16(starts + s * 2);
        const delta = view.getInt16(deltas + s * 2);
        const offset = view.getUint16(offsets + s * 2);
        for (let c = start; c <= end && c !== 0xffff; c++) {
          let glyph;
          if (offset === 0) {
            glyph = (c + delta) & 0xffff;
          } else {
            const index = offsets + s * 2 + offset + (c - start) * 2;
            glyph = view.getUint16(index);
            if (glyph) glyph = (glyph + delta) & 0xffff;
          }
          if (glyph) points.add(c);
        }
      }
    } else if (format === 12) {
      const groups = view.getUint32(at + 12);
      for (let g = 0; g < groups; g++) {
        const start = view.getUint32(at + 16 + g * 12);
        const end = view.getUint32(at + 20 + g * 12);
        for (let c = start; c <= end; c++) points.add(c);
      }
    }
  }
  return points;
}

function ranges(points) {
  const sorted = [...points].sort((a, b) => a - b);
  const out = [];
  for (const point of sorted) {
    const last = out[out.length - 1];
    if (last && point === last[1] + 1) last[1] = point;
    else out.push([point, point]);
  }
  return out;
}

const coverage = Object.fromEntries(
  Object.entries(FONTS).map(([id, file]) => [id, ranges(codePoints(file))]),
);

const output = resolve(process.cwd(), "utils/pdf/chatFontCoverage.ts");
writeFileSync(
  output,
  `// Generated by scripts/build-font-coverage.mjs from the fonts' cmap tables.
// Do not edit by hand: run the script after upgrading a font package.

/** Code points each font choice has glyphs for, as [first, last] ranges. */
export const FONT_COVERAGE: Record<string, Array<[number, number]>> = ${JSON.stringify(
    coverage,
  )};
`,
);

for (const [id, list] of Object.entries(coverage)) {
  const total = list.reduce((sum, [a, b]) => sum + b - a + 1, 0);
  console.log(`${id}: ${total} code points in ${list.length} ranges`);
}
